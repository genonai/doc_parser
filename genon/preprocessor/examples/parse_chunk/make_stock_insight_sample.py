_KEY_RE = re.compile(r'"([A-Za-z_][A-Za-z0-9_]*)":')


def split_at_key_names(text: str, count: int) -> list[str]:
    """count 조각으로 절단하되, 절단점을 **키 이름 한가운데**로 옮긴다.

    실 원천의 `"price_pat` / `tern_desc":` 를 재현하기 위해서다. 그냥 균등 절단하면
    운에 따라 값 중간에서만 끊겨, 구분자를 끼워도 우연히 통과하는 약한 샘플이 된다.
    """
    step = len(text) // count
    cuts: list[int] = []
    for i in range(1, count):
        boundary = i * step
        match = _KEY_RE.search(text, boundary)
        if match:
            key = match.group(1)
            boundary = match.start() + 1 + len(key) // 2   # 따옴표 다음, 키 이름 한가운데
        cuts.append(boundary)
    edges = [0, *cuts, len(text)]
    return [text[a:b] for a, b in zip(edges, edges[1:])]


def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Sheet"
    ws.append(HEADERS)

    rows = 0
    for stock in STOCKS:
        detail = stock["detail"]
        if isinstance(detail, (dict, list)):
            raw = json.dumps(detail, ensure_ascii=False)
            pieces = split_at_key_names(raw, stock["pieces"])
            # 자기 검증 — 이어붙여 JSON 이 복원되지 않으면 파일을 쓰지 않는다.
            assert json.loads("".join(pieces)) == detail, stock["jong_name"]
        else:
            # HTML/평문은 키 경계가 없으니 균등 절단한다(태그 중간에서도 끊긴다 — 원천과 같다).
            raw = detail
            step = len(raw) // stock["pieces"]
            edges = [0, *[i * step for i in range(1, stock["pieces"])], len(raw)]
            pieces = [raw[a:b] for a, b in zip(edges, edges[1:])]
            assert "".join(pieces) == raw, stock["jong_name"]
        for line_no, piece in enumerate(pieces, start=1):
            ws.append([
                stock["jong_name"], stock["jong_code"], stock["regt_no"], line_no, piece,
                stock["news_date"], stock["md_stck_itm_c"], stock["kosc_stck_itm_c"], stock["nat_c"],
            ])
            rows += 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT)
    print(f"{OUT}  sheet={ws.title}  rows={rows}  stocks={len(STOCKS)}")


if __name__ == "__main__":
    main()
