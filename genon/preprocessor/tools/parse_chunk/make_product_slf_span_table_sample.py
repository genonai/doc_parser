def table(page: int, index: int, head: str, rows: list[str]) -> str:
    return (f'<table data-source-page="{page}" data-table-index="{index}">\n'
            f'  <thead>\n    <tr>{head}</tr>\n  </thead>\n  <tbody>\n'
            + '\n'.join(f'    <tr>{row}</tr>' for row in rows)
            + '\n  </tbody>\n</table>')


