# 청크가 여러 개로 쪼개지는 것(splittable + chunk_prefix 반복)을 확인할 수 있다.
BR = "<BR><BR>"


def _daily(intro: str, rows: list[tuple[str, str]]) -> str:
    """일자별 관찰을 실 원천과 같은 `8월 N일 …<BR><BR>` 나열로 편다.

    관찰 문장이 이미 날짜로 시작하면 접두를 붙이지 않는다(날짜가 두 번 찍히지 않게).
    """
    parts = [note if note.startswith("8월 ") else f"8월 {day}일 {note}" for day, note in rows]
    return intro + BR + BR.join(parts)


